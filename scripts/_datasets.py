"""Dataset file guards for the scripts.

`datasets/intent/train.jsonl` is derived and not tracked (8.8 MB, regenerated byte-for-byte
from the seeds). Anything that reads a dataset file must therefore say so plainly when it is
absent, rather than continuing with less data than it thinks it has.

That is not pedantry. `injection_probe.py` reads the training split to mark which probes the
model was trained on; missing it silently would label every probe "held out" and make the
security result look BETTER than it is.
"""

from __future__ import annotations

import sys
from pathlib import Path

REGENERATE = "uv run --extra train python scripts/build_dataset.py"


def require(path: str | Path, produced_by: str = REGENERATE) -> Path:
    """Return `path`, or exit with a message naming what is missing and how to make it."""
    p = Path(path)
    if p.exists():
        return p
    sys.exit(
        f"\nmissing: {p}\n"
        f"  This file is generated, not shipped. Produce it with:\n\n"
        f"      {produced_by}\n"
    )
